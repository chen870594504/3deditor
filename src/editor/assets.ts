import { inject, type InjectionKey } from 'vue'

/**
 * 编辑器要用哪些素材，由宿主说了算。
 *
 * 这一层存在的理由只有一个：**库不许内置任何地址**。原先那份清单（含模型的
 * 相对路径）与素材根地址写死在编辑器代码里，跟着 `import.meta.env` 一起读——
 * 而库构建会把 `import.meta.env.VITE_*` 直接内联进 `dist/index.js`，
 * 于是任何一家宿主的产物里都会带上本仓库那台服务器的域名。搬进 `src/` 之前
 * 必须先把这条线剪断，剪法就是「库只认一份宿主传进来的表」。
 *
 * 库因此**一个字面量地址都不含**：`baseUrl` 空着就是空着，左栏渲染一句空态，
 * 不发任何请求、也不报错。缺省那份 `EMPTY_EDITOR_ASSETS` 就是这件事的落点。
 *
 * ## 宿主回答的是「哪一类里有什么」，不是「有哪几类」
 *
 * 有哪五类、它们的顺序、中文名、以及「这一类点一下是干什么的」，都由编辑器自己定
 * （`useModelLibrary.ts` 的 `LIBRARY_SHAPE`）。宿主给的那份表**按 key 取条目**，
 * key 不在那五个里的分类会被忽略。
 *
 * 这条分工不是随意的：`floor` / `wall` / `door` / `window` 四个 key 被
 * `TOOL_ASSET_RULES` 钉在四个绘制工具上（工具激活时要自动切到对应那一类去挑料），
 * `SidePanel.vue` 的 `SECTION_ICONS` 又要求它们是一个编译期字面量联合（新加一类
 * 忘了画图标要红）。让宿主连「有哪几类」一起定，这两处就一起失效，而失效都是
 * 静默的——点「画墙」跳到空白去，不报错。
 *
 * 要**追加**分类走 `SidePanel.vue` 的 `extraSections`：那条路才带图标与插槽。
 */

/** 一个素材条目。形状与原先那份写死在编辑器里的清单逐字一致，只是搬到了宿主这一侧 */
export interface EditorAssetEntry {
  /** 界面上显示的名字，也是追加进场景后写进 `model.name` 的值 */
  label: string
  /**
   * 素材根地址之下的**相对路径**，形如 `<分类 key>/<文件名>/<文件名>`（不带后缀）。
   *
   * 模型那一类里，它同时是几个文件的名字：目录里放同名的 `.glb` / `.png`，
   * 最终地址是 `<baseUrl><分类 key>/<file>/<file>.<ext>`。
   *
   * 空串表示**这不是一个可下载的资产**：模型那一类里它是「不联网的内置示例
   * 几何体」，天空盒那一类里它是「空盒子」那一格（点了把背景关掉）。
   * 两种都读作「没有地址可拼」，所以判它的地方一律按**空串**判，
   * 不按真假——理由见 `LibraryEntry.skybox`。
   *
   * **天空盒分类是个例外**：那个目录里放的是六张固定名字的图（`back` / `front` / …），
   * 与目录名无关，所以那边走的是另一套拼法（`resolveSkyboxFace` 解释了为什么
   * 不能合成一个函数）。这里写的是「那件事放在哪」那个名字，两种分类都成立的部分。
   */
  file: string
  /** 缩略图文件名，不写就按同名 `.png` 猜。空串表示没有图，界面回退到立方体图标 */
  thumb?: string
  /**
   * 这张贴图**一个 uv 重复铺几米见方**，可选，只对「要拿它铺一块地」的资产有意义。
   *
   * 它补偿的是「把一个模型拉伸到区域大小」这件事：铺地板时会按区域尺寸缩放模型，
   * 几何被拉伸的同时**贴图跟着拉伸**，于是图案的实物尺寸随区域大小变
   * （地基画 20 米宽，一块砖就变成 5 米）。编辑器照这个数给模型写一个 `repeat`
   * （`ModelConfig.repeat` 那边解释了机制），图案尺寸就恒定了。
   *
   * **它是这件资产的属性，不是全局常量**：同一个 2.4 米铺在只有 8 行板的地板上
   * 会得到 0.3 米宽的板。数法是在贴图里数一个 uv 重复里有几格，再乘上想要的
   * 单格尺寸——`tile1` 是 4 块砖 × 0.6 米 = 2.4，`wood` 是 12 行板 × 0.2 米 = 2.4。
   *
   * 前提是资产的 **UV 恰好铺满 0..1**（一个 uv 重复 = 整个模型），否则实际密度
   * 会被再乘上 UV 的跨度。不写这一项就是「照旧随几何拉伸」。
   */
  span?: number
  /**
   * 这个洞口**要开多大**（米），宽与高各一个，可选，只对「装进洞口」的资产有意义
   * （门与窗）：落笔时洞口按这两个数开、模型装进来一比一填满。不写就退回该种类的
   * 默认档——门是 `DOOR_WIDTH` / `DOOR_HEIGHT`（0.9 × 2.1），窗是
   * `WINDOW_WIDTH` / `WINDOW_HEIGHT`（1.2 × 1.2，窗台 0.9 米）。
   *
   * 与 `span` 是**同一性质的东西**：这件资产自己的一个数，一路原样搬到底
   * （这边 → 条目 → 拾取到的料 → 在墙上开洞），中间谁都不解释它。
   * 两个都**不是**给渲染层用的——摆法只看量出来的包围盒。
   *
   * **它是「洞口」的尺寸而不是「那一件」的尺寸**：带门套的资产量出来会比门扇宽一圈，
   * 写哪个取决于「想让墙上的洞开多大」，而墙上的洞要为整樘门窗让路，
   * 所以照资产的**整体外廓**写。
   *
   * 写错了**不报错**，只有两个方向：写小了——门比洞口宽，两侧被墙吞掉
   * （屏幕上就是「门看着怎么这么窄」）；写大了——洞口比门宽，两侧各露一条同色的缝。
   * 所以换资产时要**先量一下资产有多大，再回来改这两个数**。
   *
   * 编辑器会自己量一份（点中某一格时把 glb 拉下来量包围盒），但它**只填这里没写的
   * 那一格**：这里写的是「洞口要开多大」（一件设计决定），量出来的是「资产外廓」
   * （一件事实），而事实可以是脏的——带地面与围墙的整间房也会被量进来。
   * 所以这两个数是**权威值，不是兜底**。
   */
  width?: number
  /** 见 `width`。高同时决定缩放系数（洞高 ÷ 资产高），照资产自己的高度写就是系数 1、一个顶点都不动 */
  height?: number
}

/** 一个素材分类 */
export interface EditorAssetCategory {
  /**
   * 分类的 key，**同时是素材根地址下的目录名**（`floor` → `<baseUrl>floor/`）。
   *
   * 所以「改 key」等于「把地址指向另一个目录」：服务器上的目录没跟着改，
   * 整类就会加载失败。
   *
   * **编辑器只认它自己那五个 key**（`floor` / `wall` / `door` / `window` / `skybox`，
   * 顺序与中文名、以及「这一类点一下是干什么的」都由编辑器定，见
   * `useModelLibrary.ts` 的 `LIBRARY_SHAPE`）。写在这里的分类若 key 不在那五个里
   * **会被忽略**——不是错误，那条路（带图标、带插槽的追加分类）在
   * `SidePanel.vue` 的 `extraSections` 上。
   *
   * 为什么不让宿主连「有哪几类」一起定：那五个 key 是承重的（四个绘制工具钉在
   * 它们上面），而 `SECTION_ICONS` 那条编译期守卫要求它们是一个字面量联合。
   * 让宿主只回答「这一类里有什么」，两个问题各归各的答案。
   */
  key: string
  /**
   * 只给界面看的中文名。**可以不写**——不写就用编辑器自己的那一个。
   *
   * 留这一项是给「宿主想把『地板』叫成『地面』」这种自由；写了的胜过默认值。
   */
  label?: string
  /** 只读：宿主常常给的是 `as const` 字面量，可变数组的目标类型会拒绝它 */
  entries: readonly EditorAssetEntry[]
}

/** 编辑器要用的一整套素材：一个根地址 + 若干分类 */
export interface EditorAssets {
  /**
   * 素材根地址，末尾斜杠可有可无（拼之前会补齐）。
   *
   * **库不含任何默认值**：不传就是空串，左栏渲染空态。原先那台私有素材服务器
   * 的域名连同 dev 代理前缀一起还给了 playground——它的 CORS 与 dev 代理
   * 都是宿主自己的事。
   *
   * 连注释里都不写那个域名的字面量：sourcemap 随 `dist` 一起发出去
   * （`files` 只收 `dist`，而 `.map` 在里面），一句话会跟着进每一家宿主的产物。
   * 所以验收时那条「`dist/` 里搜不到域名与 dev 代理前缀」才搜得干净。
   */
  baseUrl: string
  categories: readonly EditorAssetCategory[]
}

/**
 * 注入键。
 *
 * 用 `provide` / `inject` 而不是模块级常量：这套值来自宿主（插件选项或组件 prop），
 * 在模块求值那一刻还不存在，而模块级常量改不成 `computed` 就得引入一份**模块级
 * 可变状态**——那是 SSR 下会串请求的写法，代价比多一个 `inject` 大得多。
 */
export const EDITOR_ASSETS_KEY: InjectionKey<EditorAssets> = Symbol('tdm-editor-assets')

/** 宿主什么都没给时的那一份：空地址、空分类。左栏据此渲染空态，不发任何请求 */
export const EMPTY_EDITOR_ASSETS: EditorAssets = { baseUrl: '', categories: [] }

/**
 * 取当前这套素材。**必须在组件 setup 里调用**（`inject` 的前提）。
 *
 * 没人在上层 provide 时退回 `EMPTY_EDITOR_ASSETS`，而不是抛错：编辑器本身要能
 * 在「宿主还没配素材」的状态下正常渲染（左栏一句空态），这比一个白屏有用得多。
 */
export function useEditorAssets(): EditorAssets {
  return inject(EDITOR_ASSETS_KEY, EMPTY_EDITOR_ASSETS)
}
