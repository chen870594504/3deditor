/**
 * 天空盒。
 *
 * 服务器上是 `skybox/bak1/` … `skybox/bak38/` 三十八个目录，编号连号，
 * 所以这里**循环生成**而不是手抄三十八行：手抄多一行少一行都不会报错，
 * 表现只是宫格里少一格、或者多一格点出来是空图。
 *
 * **每个目录里不是模型，是六张 jpg**：`back` / `down` / `front` / `left` /
 * `right` / `top`，每张一个面（见 `useModelLibrary.ts` 的 `resolveSkyboxFace`）。
 * 所以这一条的 `file` 只当**目录名**用，不与任何文件名相同——与上面几类的
 * 「目录里放同名 .glb / .png」是两套摆放约定。六张图的名字是固定的，
 * 想加一个天空盒只需要在服务器上建目录、塞六张图，这里一行都不用改。
 *
 * 数量变了就改 `SKY_BOX_COUNT`，**别去改拼名字那一行**——`bak` 后面直接跟十进制
 * 序号（`bak1`，不是 `bak01`、也不是 `bak-1`），必须与服务器上的目录名逐字一致。
 *
 * **第一格「空盒子」不是天空盒，它没有对应的服务器目录**：点它是把背景**关掉**
 * （`sun.skybox = null`），也就是回答「外面那圈现在是什么」的默认答案——
 * 配置里这个字段本来就是 `null`，所以一进编辑器这一格是亮的。详见下面那一行。
 */
const SKY_BOX_COUNT = 32

export const SKY_BOX: { label: string; file: string }[] = [
  /*
    「空盒子」排在最前面，`file` 空串。

    空串与模型那一类的内置示例几何体是同一个写法、同一个含义：**没有地址可拼**。
    到了天空盒那一支，它被拼成 `skybox: null`——不是「这一条不合格」，
    而正是「关掉」这个动作本身（`useModelLibrary.ts` 那一支有完整解释）。
    所以这里不用为它发明一个 `off: true` 之类的标记字段：**空地址已经是那个标记**，
    只是读它的地方得按「这个键在不在」判，不能按它真不真。

    排第一而不是排最后：它是这一类的「默认值」，而配置里默认就是关着的
    （`usePresets.ts` 每个预设也都写 `skybox: null`）。排在尾巴上时，
    用户得先滑过三十二格才知道「原来还能关掉」。

    这一条与下面那批不同：**它不是服务器上有的目录**——`skybox/` 下没有叫空串的
    目录。它也是这一堆里唯一一条不发任何请求的条目（`thumb` 也是空的，
    宫格会退回立方体占位图形）。

    它同时让导轨上那句数量比服务器上的目录数**多一**（那一类现在读作
    「33 个天空盒」）——量词说的是「这一类有几格」，而它就是这一类的一格。
  */
  { label: '空盒子', file: '' },
  ...Array.from(
    { length: SKY_BOX_COUNT },
    (_, i) => ({ label: `天空盒${i + 1}`, file: `bak${i + 1}` }),
  ),
]